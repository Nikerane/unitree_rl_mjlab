#!/usr/bin/env python
"""Auto-generate the trained-policy index by scanning the run dirs. FACTS (date / campaign / arm /
reward weights / iters / seeds / scene-era / final checkpoint) are extracted from each run's `params/`;
one-line SEMANTICS live in the NOTES dict below (the only thing you hand-maintain — one line per new
campaign). New policies appear automatically on the next run — no hand-kept table to go stale.

Run:  PYTHONPATH=. python evaluation/list_policies.py   ->  writes evaluation/POLICIES.md + prints a summary.
Storage convention: policies live in `logs/rsl_rl/z1_hammer/<DATE>_<TIME>_<campaign>_<arm>_seed<N>/`
(git-ignored; local + Vega). To index a different location, change ROOT below.
"""
from __future__ import annotations
import os, re, glob, collections
from pathlib import Path

ROOT = "logs/rsl_rl/z1_hammer"          # where training writes / Vega backups land
OUT = "evaluation/POLICIES.md"
L6_CUTOVER = "2026-07-06"               # L6 fixture adopted; earlier runs = gripper-era scene (not comparable)
JUNK = ("bench", "smoke", "pilot", "canary", "sanity", "clawfix")

# one-line semantics per campaign key (substring match) — maintain HERE, not in a separate doc:
NOTES = {
    "af1": "BEST — audit-fixed single strike, 100% success, 32mm",
    "mx_": "causal ablation — the swing is caused by the impact-max reward",
    "dc_": "reward decomposition — speed->swing vs impulse->straight press",
    "lg_": "1500 vs 500 iters — more training destabilizes, no ceiling break",
    "ip24": "impact_progress weight 24 sweep", "ip48": "impact_progress weight 48 (diverged 3/3)",
    "dg0": "delivered depth-gate OFF", "dg1": "delivered depth-gate ON (no-op)",
    "g1_": "8-seed maximization (none/track)", "g2_": "delivered-off (canonical FIC result)",
    "f1_": "first 8-seed campaign (timed out)", "f2_": "delivered-off (timed out, re-run as g)",
    "a05": "nail_driven 2.0->0.5 parking-farm FIX (success 0->1.00)",
    "b1_": "no-term variant (disqualified: multi-strike)",
    "nf1": "parking-farm era (pre-fix, parks <30mm)",
    "c_": "gripper-era CaT/dcmotor/hardterm lineage",
}
def note(base): return next((v for k, v in NOTES.items() if k in base), "")

def _weight(env_txt: str, term: str) -> str:
    """Arm on the `  <term>:` line, return the first following `weight:` (its block's), like the awk probe."""
    armed = False
    for ln in env_txt.splitlines():
        if re.match(rf"  {re.escape(term)}:\s*$", ln):
            armed = True
        elif armed:
            if re.match(r"  \w+:\s*$", ln):   # next reward term before a weight -> this term had none
                armed = False
            m = re.search(r"\bweight:\s*([\d.eE+-]+)", ln)
            if m: return m.group(1)
    return "?"

def scan():
    rows = collections.defaultdict(lambda: {"seeds": set(), "finals": set()})
    for d in sorted(glob.glob(f"{ROOT}/*/")):
        name = os.path.basename(d.rstrip("/"))
        m = re.match(r"(\d{4}-\d\d-\d\d)_[\d-]+_?(.*?)(?:_seed(\d+)|_s(\d+))?$", name)
        if not m:
            continue
        date, base, s1, s2 = m.group(1), m.group(2) or "(unnamed)", m.group(3), m.group(4)
        env = Path(d, "params/env.yaml"); ag = Path(d, "params/agent.yaml")
        env_txt = env.read_text() if env.exists() else ""
        impact = _weight(env_txt, "impact_progress"); deliv = _weight(env_txt, "delivered_impulse")
        it = "?"
        if ag.exists():
            mm = re.search(r"^max_iterations:\s*(\d+)", ag.read_text(), re.M)
            it = mm.group(1) if mm else "?"
        cks = glob.glob(f"{d}/model_*.pt")
        final = max((int(re.search(r"model_(\d+)", c).group(1)) for c in cks), default=None)
        key = (date, base)
        r = rows[key]; r["seeds"].add(s1 or s2 or "-")
        r["finals"].add(final if final is not None else "NONE")
        r.update(impact=impact, deliv=deliv, iters=it,
                 era="gripper" if date < L6_CUTOVER else "L6",
                 junk=any(j in base for j in JUNK) or base == "(unnamed)")
    return rows

def main():
    rows = scan()
    real = {k: v for k, v in rows.items() if not v["junk"]}
    junk = {k: v for k, v in rows.items() if v["junk"]}
    lines = ["# Trained policies — index (AUTO-GENERATED)",
             "",
             "> Generated by `evaluation/list_policies.py` — **do not edit by hand**; re-run to refresh.",
             "> Policies live in `logs/rsl_rl/z1_hammer/<DATE>_<TIME>_<campaign>_<arm>_seed<N>/` "
             "(git-ignored; local + Vega). Each run dir: `model_<final>.pt`, `params/*.yaml` (config), "
             "`git/*.diff` (provenance), `tfevents` (curves).",
             "> **Scene eras:** runs before " + L6_CUTOVER + " are gripper-era (different scene, not "
             "comparable to current L6-fixture runs).",
             "",
             f"**{len(real)} policy campaigns · {sum(len(v['seeds']) for v in real.values())} runs** "
             f"(+ {len(junk)} smoke/bench dirs, hidden).", "",
             "| date | campaign / arm | seeds | impact/deliv wt | iters | final ckpt | scene | what |",
             "|---|---|---|---:|---:|---|---|---|"]
    for (date, base), v in sorted(real.items(), reverse=True):
        seeds = ",".join(sorted(s for s in v["seeds"] if s != "-")) or "-"
        finals = "/".join(f"model_{f}" for f in sorted(f for f in v["finals"] if f != "NONE")) or "—"
        lines.append(f"| {date} | `{base}` | {seeds} | {v['impact']}/{v['deliv']} | {v['iters']} | "
                     f"{finals} | {v['era']} | {note(base)} |")
    Path(OUT).write_text("\n".join(lines) + "\n")
    print(f"-> {OUT}  ({len(real)} policy campaigns, {len(junk)} smoke/bench hidden)")
    for (date, base), v in sorted(real.items(), reverse=True)[:12]:
        print(f"  {date} {base:20s} seeds={len(v['seeds'])} wt={v['impact']}/{v['deliv']} it={v['iters']} [{v['era']}]")

if __name__ == "__main__":
    main()
